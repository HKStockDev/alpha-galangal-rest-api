    (gen_random_uuid(), 'alpha_galangal_committee_weighted_score',      'Alpha Galangal Committee: Weighted Score',      'number', 'Weighted committee score (0-100) computed from member subscores', 'snapshot', 'none', 'custom', now()),
    (gen_random_uuid(), 'alpha_galangal_committee_confidence',          'Alpha Galangal Committee: Confidence',          'number', 'Confidence (0-100) reported by the committee LLM',                   'snapshot', 'none', 'custom', now())
  on conflict (key) do nothing
  returning id
),

ins_formula as (
  insert into public.formulas
    (id, key, name, category_id, formula_level, execution_type, version, is_active, definition)
  select
    gen_random_uuid(),
    'alpha_galangal_committee_llm',
    'alpha_galangal_committee_llm',
    cat.category_id,
    'MASTER_MODEL',
    'llm',
    1,
    true,
    '{"type":"llm"}'::jsonb
  from cat
  returning id as formula_id
),

ins_prompt as (
  insert into public.formula_prompt_versions
    (id, formula_id, version, status, system_prompt, user_prompt_template, output_schema, model_name, temperature, max_output_tokens, created_at)
  select
    gen_random_uuid(),
    ins_formula.formula_id,
    1,
    'active',

    $SYS$
You are "Alpha Galangal Committee", an internal investment committee of six notable investors:
- Warren Buffett (20%) — Moat & intrinsic value
- Michael Burry (15%) — Contrarian deep value / dislocation
