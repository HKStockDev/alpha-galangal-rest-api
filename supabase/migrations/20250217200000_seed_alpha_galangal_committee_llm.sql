{
  "ticker": "",
  "member_scores": {
    "buffett": 0,
    "burry": 0,
    "druckenmiller": 0,
    "wood": 0,
    "graham": 0,
    "lynch": 0
  },
  "weighted_score": 0,
  "confidence": 0,
  "summary": "",
  "key_strengths": [],
  "key_risks": []
}

Constraints:
- summary must be <= 3 sentences
- do not fabricate missing financial values; if missing, reflect uncertainty in confidence
$USR$,

    '{
      "required_keys": ["ticker","member_scores","weighted_score","confidence","summary","key_strengths","key_risks"],
      "member_keys": ["buffett","burry","druckenmiller","wood","graham","lynch"]
    }'::jsonb,

    'gemini-2.5-flash',
    0.2,
    800,
    now()
  from ins_formula
  returning id as prompt_version_id, formula_id
)

update public.formulas f
set active_prompt_version_id = ins_prompt.prompt_version_id
from ins_prompt
where f.id = ins_prompt.formula_id;
