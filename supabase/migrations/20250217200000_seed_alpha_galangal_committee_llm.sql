with cat as (
  select id as category_id
  from public.signal_categories
  where name = 'INTELLIGENCE_SYNTHESIS'
  limit 1
),

ins_factors as (
  insert into public.factors
    (id, key, name, value_type, description, data_grain, period_supported, statement_type, created_at)
  values
    (gen_random_uuid(), 'alpha_galangal_committee_buffett_score',       'Alpha Galangal Committee: Buffett Score',       'number', 'Subscore (0-100) generated by the committee LLM for Buffett',       'snapshot', 'none', 'custom', now()),
    (gen_random_uuid(), 'alpha_galangal_committee_wood_score',          'Alpha Galangal Committee: Wood Score',          'number', 'Subscore (0-100) generated by the committee LLM for Cathie Wood',    'snapshot', 'none', 'custom', now()),
    (gen_random_uuid(), 'alpha_galangal_committee_lynch_score',         'Alpha Galangal Committee: Lynch Score',         'number', 'Subscore (0-100) generated by the committee LLM for Peter Lynch',    'snapshot', 'none', 'custom', now()),
    (gen_random_uuid(), 'alpha_galangal_committee_burry_score',         'Alpha Galangal Committee: Burry Score',         'number', 'Subscore (0-100) generated by the committee LLM for Michael Burry',  'snapshot', 'none', 'custom', now()),
    (gen_random_uuid(), 'alpha_galangal_committee_druckenmiller_score', 'Alpha Galangal Committee: Druckenmiller Score', 'number', 'Subscore (0-100) generated by the committee LLM for Druckenmiller',  'snapshot', 'none', 'custom', now()),
