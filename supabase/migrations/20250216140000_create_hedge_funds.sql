  pct_in_top_10 numeric,
  perf_equal_qoq numeric,
  perf_equal_all numeric,
  perf_mgr_qoq numeric,
  perf_mgr_all numeric,
  earliest_13f timestamptz,
  perf_equal_1_year numeric,
  perf_equal_5_year numeric,
  perf_mgr_wt_1_year numeric,
